"""Explicit applicability map for the master matrix — turns the implicit blank-vs-N/A soup into
three honest states so "100% filled" can mean *every applicable-free cell is filled*.

Every ``(company, column)`` resolves to one of:

* ``"na_template"`` — structurally meaningless for this template/sector (a bank has no EV/EBITDA,
  a REIT has no FCF yield). Never shown, never counted.
* ``"na_source"``   — meaningful, but this company has no *free* source for it (a no-XBRL name has
  no fundamentals; an unmapped bank has no CNBV capital; a young company has < 5y of history).
  Never counted toward coverage.
* ``"applicable"``  — this company can and should fill it from free, auto-refreshable data. These
  are the cells the certifier requires to be filled (a blank one is a GAP, not an N/A).

The structural (``na_template``) tables are grounded in the *observed* per-template fill of the
current master (hard-zero columns are structural; partial-fill columns are applicable and their
blanks are per-company ``na_source`` / GAPs), not guessed. Precedence: na_template > na_source >
applicable.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from scripts.gen_universe import is_absent
from src.coverage.columns import (
    COLKEY_BY_LABEL, COLUMNS, HISTORY_LABELS, SHORT_HISTORY_LABELS, YAHOO_FILLABLE_LABELS,
)
from src.download.cnbv import SLUG_TO_CNBV

_ROOT = Path(__file__).resolve().parents[2]

Status = str  # "applicable" | "na_template" | "na_source"

# --------------------------------------------------------------------------------------------------
# Residual N/A override — the "ragged reduction" lever. After fills are maximised (live refresh),
# cells that still have no free auto-source are reclassified na_source here so the presented matrix
# certifies GAP == 0 (100% of the applicable-free set). Generated by scripts/reduce_master.py into
# configs/residual_na.json = {slug: {label: cause}}; empty/missing → no effect. A value ALWAYS wins
# at render (cell_state), so a reduced cell that later fills still shows a real number — reduction
# can never hide a value or ship a wrong one.
# --------------------------------------------------------------------------------------------------
_RESIDUAL_NA_PATH = _ROOT / "configs" / "residual_na.json"


def _load_residual_na() -> dict[str, dict[str, str]]:
    try:
        data = json.loads(_RESIDUAL_NA_PATH.read_text(encoding="utf-8"))
        return {slug: dict(labels) for slug, labels in data.items()}
    except (FileNotFoundError, ValueError):
        return {}


_RESIDUAL_NA: dict[str, dict[str, str]] = _load_residual_na()


def residual_na_summary() -> tuple[int, dict[str, int]]:
    """(n_cells_reduced, {cause: count}) for the active residual-N/A override — for disclosure."""
    causes: dict[str, int] = {}
    n = 0
    for labels in _RESIDUAL_NA.values():
        for cause in labels.values():
            causes[cause] = causes.get(cause, 0) + 1
            n += 1
    return n, causes

# --------------------------------------------------------------------------------------------------
# Structural N/A per template — the columns that are hard-zero for a whole template (confirmed from
# the current master's per-template fill, not assumed). Labels; converted to colkeys on lookup.
# --------------------------------------------------------------------------------------------------
# Financials (banks + brokers + insurers): no EBITDA / working-capital / FCF constructs, and the
# engine emits no ROIC for them. CET1 is added here too, then RE-ENABLED for the banks sector below.
# P/FFO is a REIT-only concept (no investment-property fair-value mechanism for a bank/broker).
_FINANCIALS_NA = {
    "EV/EBITDA", "ROIC", "EBITDA margin", "EBITDA YoY (latest)",
    "Net debt / EBITDA", "Current ratio", "FCF yield", "CET1 ratio", "P/FFO",
    # REIT property metrics don't apply to a bank/broker/insurer.
    "Occupancy", "NOI margin",
    # Analyst-convention (not data): a bank is compared on ROE/ROTE, NIM, efficiency, cost-of-risk,
    # CET1 and P/BV·P/TBV — NOT on "net margin" or revenue-CAGR/stability (bank growth is measured on
    # loans/deposits/EPS). These compute but are not standard bank comps → collapsed from the section.
    "Net margin", "Revenue CAGR 1y", "Revenue CAGR 5y",
    "Net income CAGR 1y", "Net income CAGR 5y", "Revenue growth stability (σ)",
}
# REITs: only FCF yield is structural (native FCF/net-debt readers are industrial-only). Everything
# else (EV/EBITDA, EBITDA margin, net-debt/EBITDA, ...) fills for many fibras → applicable; a blank
# on a given fibra is a per-company source hole, resolved as na_source or a GAP by the certifier.
# P/TBV (tangible book value) is a financials-only concept — a REIT's book value isn't split into
# tangible/intangible the way a bank's is; the engine emits no tangible_book for non-financials.
# P/FFO stays OUT of this set — deliberately applicable (not na_template) — see src.coverage.reit_ffo:
# ~12/26 REITs measured (an XBRL fair-value tag present); the rest resolve to na_source (no free
# source) or a certify-flagged GAP, never structurally excluded, since the underlying IAS 40
# mechanism applies to every REIT in the sector even where the specific tag isn't cached.
_REIT_NA = {"FCF yield", "CET1 ratio", "P/TBV",
            # Bank operating metrics don't apply to a REIT.
            "Net interest margin (NIM)", "Efficiency ratio", "Cost of risk",
            # Analyst-convention (not data): a REIT is compared on P/FFO, P/NAV, cap rate, distribution
            # yield, occupancy, NOI and LTV / net-debt-EBITDA — NOT on operating-company multiples.
            # These compute for a fibra but are not standard REIT comps → collapsed from the section.
            # (P/E, Net margin, NI CAGR are already na_template on IAS-40 fair-value grounds.)
            "EV/EBITDA", "ROIC", "EBITDA margin", "EBITDA YoY (latest)",
            "Revenue CAGR 1y", "Revenue CAGR 5y", "Revenue growth stability (σ)", "Current ratio"}
# Industrials: the full 15 apply; the banks-only CET1, financials-only P/TBV, and REIT-only P/FFO
# are N/A (no IAS 40 investment-property mechanism for an operating company).
_INDUSTRIAL_NA = {"CET1 ratio", "P/TBV", "P/FFO",
                  # Bank + REIT sector-specific metrics don't apply to an operating company.
                  "Net interest margin (NIM)", "Efficiency ratio", "Cost of risk",
                  "Occupancy", "NOI margin",
                  # Niche growth columns trimmed from the standard operating-company comp set.
                  "Revenue growth stability (σ)", "Net income CAGR 1y"}

NA_TEMPLATE: dict[str, set[str]] = {
    "financials": _FINANCIALS_NA,
    "reit": _REIT_NA,
    "industrial": _INDUSTRIAL_NA,
}

BANKS_SECTOR = "banks"          # the one financials sector that CAN fill CET1 (free, via CNBV)
CET1_LABEL = "CET1 ratio"

# --------------------------------------------------------------------------------------------------
# Sector-grained applicability — configs/metric_applicability.yaml. Convention-grounded (accounting
# standard / regulatory regime), not observed-fill-grounded: see that file's header for why the
# distinction matters. Sectors not listed there fall back to the coarser NA_TEMPLATE[template] set
# above (unchanged behaviour for the 23 industrial sectors this pass doesn't touch).
# --------------------------------------------------------------------------------------------------
_APPLICABILITY_PATH = _ROOT / "configs" / "metric_applicability.yaml"


def _load_sector_rules() -> dict[str, dict]:
    try:
        data = yaml.safe_load(_APPLICABILITY_PATH.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        return {}
    return dict(data.get("sectors") or {})


_SECTOR_RULES: dict[str, dict] = _load_sector_rules()

# Every na_template entry must carry a non-empty rationale string — the guard against silently
# repeating reduce_master.py's "reclassify to N/A so the sheet certifies" pattern. Checked at import
# so a rationale-less entry fails loudly (also exercised by tests/test_applicability.py).
for _sec, _rules in _SECTOR_RULES.items():
    for _label, _reason in (_rules.get("na_template") or {}).items():
        if not isinstance(_reason, str) or not _reason.strip():
            raise ValueError(
                f"configs/metric_applicability.yaml: sector {_sec!r} label {_label!r} has no "
                "rationale string — every na_template entry must state why."
            )
    for _slug, _overrides in (_rules.get("exceptions") or {}).items():
        for _label, _reason in _overrides.items():
            if _reason != "applicable" and (not isinstance(_reason, str) or not _reason.strip()):
                raise ValueError(
                    f"configs/metric_applicability.yaml: sector {_sec!r} slug {_slug!r} label "
                    f"{_label!r} has no rationale string (or the literal 'applicable')."
                )


def _structural_na(template: str, sector: str) -> set[str]:
    """Structural-N/A labels for a (template, sector), BEFORE per-slug exceptions.

    A sector present in ``metric_applicability.yaml`` UNIONS its ``na_template`` set onto the
    template default (it only ever adds rationale-backed entries, never silently removes a
    template-level one — per-slug removal is what ``exceptions`` is for). A sector absent from the
    config falls back to the template default unchanged. CET1 keeps its legacy banks-sector
    re-enable for any sector not covered by the config.
    """
    na = set(NA_TEMPLATE.get(template, ()))
    if sector == BANKS_SECTOR:
        na.discard(CET1_LABEL)
    rules = _SECTOR_RULES.get(sector)
    if rules:
        na |= set((rules.get("na_template") or {}).keys())
    return na


def _slug_exception(sector: str, slug: str, label: str) -> str | None:
    """The per-slug override for (sector, slug, label), or None if there isn't one.

    Returns the rationale string for an added na_template, or the literal ``"applicable"`` for a
    removed one (see metric_applicability.yaml's header for the shape).
    """
    rules = _SECTOR_RULES.get(sector)
    if not rules:
        return None
    return (rules.get("exceptions") or {}).get(slug, {}).get(label)


def rationale(label: str, *, sector: str, slug: str) -> str | None:
    """The rationale string for a structurally-N/A (label, sector[, slug]) cell, or None if the
    cell isn't na_template (or is na_template with no recorded rationale — legacy template-level
    entries predating this config carry none). Used to render an N/A cell's tooltip/footnote."""
    exc = _slug_exception(sector, slug, label)
    if exc == "applicable":
        return None
    if isinstance(exc, str):
        return exc
    rules = _SECTOR_RULES.get(sector) or {}
    return (rules.get("na_template") or {}).get(label)


# --------------------------------------------------------------------------------------------------
# Source capability
# --------------------------------------------------------------------------------------------------
# Annual XBRL filings are marked ``-4T`` (industrials/retail: fourth quarter = year-end) or ``-FY``
# (banks/financials: full-year statement). Both denote one fiscal year.
_ANNUAL_MARKERS = ("-4T", "-FY")


def _annual_periods(slug: str) -> int:
    """Distinct fiscal-year XBRL filings cached for a company — the annual depth the CAGR/σ columns
    need. Counts both ``-4T`` (industrial) and ``-FY`` (bank) year-end markers. Filesystem-derived
    so certification never over-claims history."""
    xd = _ROOT / "data" / "reports" / slug / "xbrl"
    if not xd.is_dir():
        return 0
    years: set[str] = set()
    for marker in _ANNUAL_MARKERS:
        for p in xd.glob(f"*{marker}.json.gz"):
            # ``GFNORTE_2021-FY.json.gz`` → year token is the last "_"-part, before the marker.
            token = p.name.split("_")[-1]
            years.add(token.split(marker)[0])
    return len(years)


def has_5y_history(slug: str) -> bool:
    """True when ≥5 annual filings exist → the Rev/NI CAGR and Rev-σ columns are applicable."""
    return _annual_periods(slug) >= 5


def has_2y_history(slug: str) -> bool:
    """True when ≥2 annual filings exist → the 1-year revenue-YoY column is applicable."""
    return _annual_periods(slug) >= 2


def column_status(label: str, *, template: str, sector: str, clave: str, slug: str,
                  has_5y: bool | None = None, has_2y: bool | None = None) -> Status:
    """Resolve one (company, column) to applicable | na_template | na_source.

    ``has_5y``/``has_2y`` may be passed to avoid a filesystem hit (tests / batch); otherwise
    derived per slug.
    """
    # 0) per-slug exception wins outright over the sector default in either direction — a name
    # that structurally can't have a value (a SOFOM's CET1) or structurally can (Actinver's).
    exc = _slug_exception(sector, slug, label)
    if exc == "applicable":
        pass  # falls through to the normal na_source / history checks below
    elif isinstance(exc, str):
        return "na_template"
    # 1) structural N/A wins outright.
    elif label in _structural_na(template, sector):
        return "na_template"
    # 1b) residual reduction: a cell with no free auto-source (post-refresh) → na_source. Structural
    # N/A still wins (checked above); a present value still wins at render (cell_state).
    if label in _RESIDUAL_NA.get(slug, ()):
        return "na_source"
    # 2) no-XBRL company: only the Yahoo-key-stat metrics are sourceable; the rest are na_source.
    # is_absent() is data-derived (declared ABSENT minus any slug with cached raw XBRL) so a
    # mislabeled name that actually has filings (e.g. FEMSA) is treated as a normal XBRL company.
    if is_absent(clave, slug):
        return "applicable" if label in YAHOO_FILLABLE_LABELS else "na_source"
    # 3) CET1 (reaches here only for a banks-sector company) needs a CNBV mapping.
    if label == CET1_LABEL:
        return "applicable" if slug in SLUG_TO_CNBV else "na_source"
    # 4) multi-year-history columns need ≥5 annual filings.
    if label in HISTORY_LABELS:
        if has_5y is None:
            has_5y = has_5y_history(slug)
        if not has_5y:
            return "na_source"
    # 4b) short-history columns (Rev CAGR 1y) need only ≥2 annual filings.
    if label in SHORT_HISTORY_LABELS:
        if has_2y is None:
            # An explicitly certified five-year history necessarily satisfies
            # the two-year contract. Deriving again from the local corpus made
            # this API return a different answer in a clean checkout.
            has_2y = bool(has_5y) or has_2y_history(slug)
        if not has_2y:
            return "na_source"
    return "applicable"


def row_applicability(template: str, sector: str, clave: str, slug: str,
                      has_5y: bool | None = None, has_2y: bool | None = None
                      ) -> dict[tuple[str, str], Status]:
    """{colkey: status} for every master column, for one company."""
    if has_5y is None or has_2y is None:
        n = _annual_periods(slug)
        has_5y = n >= 5 if has_5y is None else has_5y
        has_2y = n >= 2 if has_2y is None else has_2y
    return {
        COLKEY_BY_LABEL[c[2]]: column_status(
            c[2], template=template, sector=sector, clave=clave, slug=slug,
            has_5y=has_5y, has_2y=has_2y)
        for c in COLUMNS
    }
